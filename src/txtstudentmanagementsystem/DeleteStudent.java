    private void btnDeleteStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteStudentActionPerformed


    String id = txtId.getText();

    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter Student Id");
        return;
    }

    try {
        File f1 = new File("Student.txt");
        Scanner input = new Scanner(f1);

        String data = "";
        boolean found = false;

        while (input.hasNextLine()) {

            String line = input.nextLine();
            String[] rowData = line.split(",");

            if (rowData[0].equalsIgnoreCase(id)) {
                found = true;
            } else {
                data += line + "\n";
            }
        }

        input.close();

        if (found == true) {

            FileWriter fw = new FileWriter(f1);
            fw.write(data);
            fw.close();

            JOptionPane.showMessageDialog(
                    this, "Student Deleted Successfully!"
            );

            txtId.setText("");
            txtNic.setText("");
            txtName.setText("");
            txtPrfMarks.setText("");
            txtDbmsMarks.setText("");
            txtGpa.setText("");

            txtId.requestFocus();

        } else {
            JOptionPane.showMessageDialog(this, "Student Not Found!");
        }

    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error accessing Student.txt");
    }


    
    }//GEN-LAST:event_btnDeleteStudentActionPerformed

