    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        

    if (txtBatchNum.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter Batch Number");
        return;
    }

    int batchNumber = Integer.parseInt(txtBatchNum.getText().trim());

    boolean exists = false;

    File file = new File("Batch.txt");

    try {
        if (file.exists()) {
            Scanner input = new Scanner(file);

            while (input.hasNextLine()) {
                String line = input.nextLine().trim();

                if (!line.isEmpty()) {
                    int savedBatchNumber = Integer.parseInt(line.split(",")[0]);

                    if (savedBatchNumber == batchNumber) {
                        exists = true;
                        break;
                    }
                }
            }

            input.close();
        }

        if (exists) {
            JOptionPane.showMessageDialog(this, "Batch Number already exists!");
        } else {
            FileWriter fw = new FileWriter(file, true);
            fw.write(batchNumber + ",1\n");
            fw.close();

            JOptionPane.showMessageDialog(this, "Batch added successfully!");
            txtBatchNum.setText("");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }


  

    }//GEN-LAST:event_jButton1ActionPerformed

