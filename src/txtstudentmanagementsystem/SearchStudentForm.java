    private void txtIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActionPerformed
        try {
            String id=txtId.getText();
            if (id.isEmpty()) {
                JOptionPane.showMessageDialog(this,"Please Enter Student ID" );
                return;
            }
            File f1=new File("Student.txt");
            Scanner input=new Scanner(f1);
            
            boolean found=false;
            while(input.hasNextLine()){
                String line=input.nextLine();
                String[] rowData=line.split(",");
                
                if(rowData[0].equalsIgnoreCase(id)){
                    txtId.setText(rowData[0]);
                    txtNic.setText(rowData[1]);
                    txtName.setText(rowData[2]);
                    
                    int prfMarks=Details.getPrfMarks(rowData);
                    int dbmsMarks=Details.getDbmsMarks(rowData);
                    
                    txtPrfMarks.setText(String.valueOf(prfMarks));
                    txtDbmsMarks.setText(String.valueOf(dbmsMarks));
                    
                    double gpa=Details.getGPA(prfMarks, dbmsMarks);
                    if(gpa==-1){
                        txtGpa.setText(" Abesent");
                    }
                    else if(gpa==-2){
                        txtGpa.setText("New Student");
                    }
                    else{
                        txtGpa.setText(String.valueOf(gpa));
                    }
                    found=true;
                    break;
                }
            }
            input.close();
            
            if(found==false){
                JOptionPane.showMessageDialog(this, "Student not Found");
                
                txtNic.setText("");
                txtName.setText("");
                txtPrfMarks.setText("");
                txtDbmsMarks.setText("");
                txtGpa.setText("");
                
            }   } catch (FileNotFoundException ex) {
            java.util.logging.Logger.getLogger(SearchStudentForm.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        }


 
          
    }//GEN-LAST:event_txtIdActionPerformed

