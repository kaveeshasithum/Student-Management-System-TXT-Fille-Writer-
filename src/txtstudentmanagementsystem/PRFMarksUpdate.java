    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
 
    try {
        String id = txtId.getText();
        String name = txtName.getText();
        String nic = txtNic.getText();
        int prfMarks = Integer.parseInt(txtPrfMarks.getText());

        File f1 = new File("Student.txt");
        Scanner input = new Scanner(f1);

        String data = "";
        boolean found = false;

        while (input.hasNextLine()) {

            String line = input.nextLine();
            String[] rowData = line.split(",");

            if (rowData[0].equalsIgnoreCase(id)) {

                data += rowData[0] + ","
                      + rowData[1] + ","
                      + rowData[2] + ","
                      + prfMarks + ","
                      + rowData[4] + "\n";

                found = true;

            } else {
                data += line + "\n";
            }
        }

        input.close();

        if (found) {
            FileWriter fw = new FileWriter(f1);
            fw.write(data);
            fw.close();

            JOptionPane.showMessageDialog(this, "PRF Marks Updated Successfully!");

        } else {
            JOptionPane.showMessageDialog(this, "Student not found");
        }

        } catch (FileNotFoundException ex) {
            JOptionPane.showMessageDialog(this, "Student.txt file not found!");

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Enter valid PRF marks!");

        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }


    }//GEN-LAST:event_jButton2ActionPerformed

