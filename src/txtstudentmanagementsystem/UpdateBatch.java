    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed


    int batchNumber;

    try {
        batchNumber = Integer.parseInt(txtBatchNumber.getText().trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Enter valid batch number");
        return;
    }

    if (!jCheckBoxOpen.isSelected() && !jCheckBoxClosed.isSelected()) {
        JOptionPane.showMessageDialog(this, "Select enrollment status");
        return;
    }

    int status = jCheckBoxOpen.isSelected() ? 1 : 0;

    try {
        File file = new File("Batch.txt");
        Scanner input = new Scanner(file);

        String content = "";
        boolean found = false;

        while (input.hasNextLine()) {

            String line = input.nextLine();
            String[] data = line.split(",");

            if (Integer.parseInt(data[0].trim()) == batchNumber) {
                content += batchNumber + "," + status + "\n";
                found = true;
            } else {
                content += line + "\n";
            }
        }

        input.close();

        if (found) {

            FileWriter fw = new FileWriter(file);
            fw.write(content);
            fw.close();

            JOptionPane.showMessageDialog(this, "Batch updated successfully");

        } else {
            JOptionPane.showMessageDialog(this, "Batch not found");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }




    }//GEN-LAST:event_jButton1ActionPerformed

