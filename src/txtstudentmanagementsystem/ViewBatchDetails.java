    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed


       try {
           DefaultTableModel dtm=(DefaultTableModel)tblBatchDetails.getModel();
           dtm.setRowCount(0);
           
           File file=new File("Batch.txt");
           if(!file.exists()){
               JOptionPane.showMessageDialog(this, "Batch not found !");
               return;
           }
           Scanner input=new Scanner(file);
           int no=1;
           while(input.hasNextLine()){
               String line=input.nextLine();
               if(line.isEmpty()){
                   continue;
               }
               String[]data=line.split(",");
               int batchNumber=Integer.parseInt(data[0]);
               int batchStatus=Integer.parseInt(data[1]);
               
               String status;
               
               if (batchStatus == 1) {
                   status = "ENROLLMENT OPEN";
               } else {
                   status = "ENROLLMENT CLOSED";
               }
               int studentCount=0;
               File studentFile=new File("Student.txt");
               if(studentFile.exists()){
                   try (Scanner studentInput = new Scanner(studentFile)) {
                       while (studentInput.hasNextLine()) {
                           String studentLine = studentInput.nextLine();
                           
                           if (studentLine.isEmpty()) {
                               continue;
                           }
                           String[] studentData = studentLine.split(",");
                           String studentId = studentData[0];
                           if (studentId.length() >= 7) {
                               int studentBatch = Integer.parseInt(studentId.substring(4, 7));
                               if (studentBatch == batchNumber) {
                                   studentCount++;
                               }
                               
                           }
                       }
                   } catch (FileNotFoundException ex) {
                       Logger.getLogger(ViewBatchDetails.class.getName()).log(Level.SEVERE, null, ex);
                   }
               }
               dtm.addRow(new Object[]{no, batchNumber, studentCount, status });
               
               no++;
               
           }
           input.close();
           // TODO add your handling code here:
       } catch (FileNotFoundException ex) {
           Logger.getLogger(ViewBatchDetails.class.getName()).log(Level.SEVERE, null, ex);
       }
    }//GEN-LAST:event_jButton2ActionPerformed

